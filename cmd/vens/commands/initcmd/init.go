// Package initcmd implements `vens init`: an interactive prompt that writes
// a config.yaml for `vens generate`, so a new user does not have to copy
// examples/quickstart/config.yaml and guess which fields are required.
package initcmd

import (
	"bufio"
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/spf13/cobra"
	"go.yaml.in/yaml/v3"

	"github.com/venslabs/vens/pkg/riskconfig"
)

// New returns the `vens init` command.
func New() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "init",
		Short: "Interactively generate a config.yaml for vens generate",
		Long: `Ask a short series of questions about the system being scored and
write the answers as a config.yaml that vens generate accepts. Only the
project name and the three required context fields are mandatory; every
other question can be skipped with Enter. An existing file is left alone
unless --force is passed.`,
		Example: `  vens init
  vens init --output my-config.yaml
  vens init --force`,
		Args: cobra.NoArgs,
		RunE: action,
	}

	flags := cmd.Flags()
	flags.StringP("output", "o", "config.yaml", "Path of the config file to write")
	flags.Bool("force", false, "Overwrite the output file if it already exists")

	return cmd
}

func action(cmd *cobra.Command, args []string) error {
	flags := cmd.Flags()
	output, err := flags.GetString("output")
	if err != nil {
		return err
	}
	force, err := flags.GetBool("force")
	if err != nil {
		return err
	}
	if _, err := os.Stat(output); err == nil && !force {
		return fmt.Errorf("config file %q already exists (use --force to overwrite)", output)
	} else if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("checking output file %q: %w", output, err)
	}

	p := &prompter{in: bufio.NewReader(cmd.InOrStdin()), out: cmd.OutOrStdout()}

	cfg := riskconfig.Config{}
	cfg.Project.Name, err = p.askRequired("Project name")
	if err != nil {
		return err
	}
	cfg.Project.Description, err = p.askOptional("Project description")
	if err != nil {
		return err
	}
	cfg.Context.Exposure, err = p.askChoice("Exposure", []string{"internal", "private", "internet"})
	if err != nil {
		return err
	}
	cfg.Context.DataSensitivity, err = p.askChoice("Data sensitivity", []string{"low", "medium", "high", "critical"})
	if err != nil {
		return err
	}
	cfg.Context.BusinessCriticality, err = p.askChoice("Business criticality", []string{"low", "medium", "high", "critical"})
	if err != nil {
		return err
	}
	if v, err := p.askOptionalChoice("Availability requirement", []string{"low", "medium", "high", "critical"}); err != nil {
		return err
	} else if v != "" {
		cfg.Context.AvailabilityRequirement = &v
	}
	if v, err := p.askCompliance(); err != nil {
		return err
	} else {
		cfg.Context.ComplianceRequirements = v
	}
	if v, err := p.askOptionalChoice("Audit requirement", []string{"low", "medium", "high"}); err != nil {
		return err
	} else if v != "" {
		cfg.Context.AuditRequirement = &v
	}
	cfg.Context.Notes, err = p.askOptional("Notes")
	if err != nil {
		return err
	}

	body, err := yaml.Marshal(&cfg)
	if err != nil {
		return fmt.Errorf("encoding config: %w", err)
	}
	// Parse it back before writing: the file must be one `vens generate`
	// accepts, not just one that looks right.
	if _, err := riskconfig.Parse(body); err != nil {
		return fmt.Errorf("generated config failed validation: %w", err)
	}
	out := "# Generated by `vens init`. Edit any value, then run:\n" +
		"#   vens generate --config-file " + output + " report.json vex.cdx.json\n" +
		string(body)
	if err := os.WriteFile(output, []byte(out), 0644); err != nil {
		return fmt.Errorf("writing config file %q: %w", output, err)
	}
	if _, err := fmt.Fprintf(cmd.OutOrStdout(), "Wrote %s\n", output); err != nil {
		return fmt.Errorf("writing output: %w", err)
	}
	return nil
}

// prompter asks one question per line on stdin and echoes nothing back:
// the caller's answers stay in their terminal, not in the file.
type prompter struct {
	in  *bufio.Reader
	out io.Writer
}

func (p *prompter) readLine() (string, error) {
	line, err := p.in.ReadString('\n')
	if err != nil && err != io.EOF {
		return "", err
	}
	if err == io.EOF && line == "" {
		return "", io.EOF
	}
	return strings.TrimSpace(line), nil
}

func (p *prompter) askRequired(question string) (string, error) {
	for {
		if _, err := fmt.Fprintf(p.out, "%s: ", question); err != nil {
			return "", fmt.Errorf("writing prompt: %w", err)
		}
		answer, err := p.readLine()
		if err != nil {
			return "", fmt.Errorf("reading %q: %w", question, err)
		}
		if answer != "" {
			return answer, nil
		}
		if _, err := fmt.Fprintln(p.out, "A value is required."); err != nil {
			return "", fmt.Errorf("writing prompt: %w", err)
		}
	}
}

func (p *prompter) askOptional(question string) (string, error) {
	if _, err := fmt.Fprintf(p.out, "%s (optional, Enter to skip): ", question); err != nil {
		return "", fmt.Errorf("writing prompt: %w", err)
	}
	answer, err := p.readLine()
	if err != nil {
		return "", fmt.Errorf("reading %q: %w", question, err)
	}
	return answer, nil
}

func (p *prompter) askChoice(question string, valid []string) (string, error) {
	for {
		if _, err := fmt.Fprintf(p.out, "%s [%s]: ", question, strings.Join(valid, "/")); err != nil {
			return "", fmt.Errorf("writing prompt: %w", err)
		}
		answer, err := p.readLine()
		if err != nil {
			return "", fmt.Errorf("reading %q: %w", question, err)
		}
		for _, v := range valid {
			if strings.EqualFold(answer, v) {
				return v, nil
			}
		}
		if _, err := fmt.Fprintf(p.out, "Must be one of: %s.\n", strings.Join(valid, ", ")); err != nil {
			return "", fmt.Errorf("writing prompt: %w", err)
		}
	}
}

func (p *prompter) askOptionalChoice(question string, valid []string) (string, error) {
	for {
		if _, err := fmt.Fprintf(p.out, "%s (optional) [%s]: ", question, strings.Join(valid, "/")); err != nil {
			return "", fmt.Errorf("writing prompt: %w", err)
		}
		answer, err := p.readLine()
		if err != nil {
			return "", fmt.Errorf("reading %q: %w", question, err)
		}
		if answer == "" {
			return "", nil
		}
		for _, v := range valid {
			if strings.EqualFold(answer, v) {
				return v, nil
			}
		}
		if _, err := fmt.Fprintf(p.out, "Must be one of: %s.\n", strings.Join(valid, ", ")); err != nil {
			return "", fmt.Errorf("writing prompt: %w", err)
		}
	}
}

func (p *prompter) askCompliance() ([]string, error) {
	valid := []string{"PCI-DSS", "HIPAA", "GDPR", "SOX", "ISO27001", "FedRAMP", "NIST", "CCPA", "SOC2", "FISMA", "ITAR", "CMMC"}
	for {
		if _, err := fmt.Fprintf(p.out, "Compliance requirements, comma-separated (optional) [%s]: ", strings.Join(valid, ", ")); err != nil {
			return nil, fmt.Errorf("writing prompt: %w", err)
		}
		answer, err := p.readLine()
		if err != nil {
			return nil, fmt.Errorf("reading compliance requirements: %w", err)
		}
		if answer == "" {
			return nil, nil
		}
		var chosen []string
		unknown := ""
		for _, part := range strings.Split(answer, ",") {
			part = strings.TrimSpace(part)
			if part == "" {
				continue
			}
			matched := false
			for _, v := range valid {
				if strings.EqualFold(part, v) {
					chosen = append(chosen, v)
					matched = true
					break
				}
			}
			if !matched {
				unknown = part
				break
			}
		}
		if unknown != "" {
			if _, err := fmt.Fprintf(p.out, "Unknown framework %q (valid: %s).\n", unknown, strings.Join(valid, ", ")); err != nil {
			return nil, fmt.Errorf("writing prompt: %w", err)
		}
			continue
		}
		return chosen, nil
	}
}
